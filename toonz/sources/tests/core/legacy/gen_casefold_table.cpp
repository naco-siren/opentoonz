// Prints common/tcore/tcasefoldtable.inc: the simple case folding of
// QChar::toCaseFolded (Qt 5), which QString::compare(..., Qt::CaseInsensitive)
// compares by. tstring.cpp uses it to tell two names apart as QFile::rename
// did (doc/nexttoonz_core_noqt.md, step 6a); test_tstring_qt.cpp checks
// every code point against Qt again.
//
//   c++ -std=c++17 -F<qt>/lib -I<qt>/lib/QtCore.framework/Headers \
//       gen_casefold_table.cpp -F<qt>/lib -framework QtCore -o gen
//   ./gen > ../../../common/tcore/tcasefoldtable.inc
#include <QChar>
#include <cstdio>

int main() {
  printf("// Generated by tests/core/legacy/gen_casefold_table.cpp from Qt %s.\n",
         QT_VERSION_STR);
  printf("// {code point, its simple case folding} for every code point\n");
  printf("// QChar::toCaseFolded changes, in order.\n");
  for (uint c = 0; c <= 0x10ffff; ++c) {
    if (c >= 0xd800 && c <= 0xdfff) continue;
    uint f = QChar::toCaseFolded(c);
    if (f != c) printf("{0x%X, 0x%X},\n", c, f);
  }
  return 0;
}
