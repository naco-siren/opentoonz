// Prints common/tcore/tlowercasetable.inc: the lowercase mapping of
// QString::toLower (Qt 5), one code point at a time. tstring.cpp uses it to
// lower strings exactly as QString did (doc/nexttoonz_core_noqt.md, step 4);
// test_tstring_qt.cpp checks every code point against Qt again.
//
//   c++ -std=c++17 -F<qt>/lib -I<qt>/lib/QtCore.framework/Headers \
//       gen_lowercase_table.cpp -F<qt>/lib -framework QtCore -o gen
//   ./gen > ../../../common/tcore/tlowercasetable.inc
#include <QString>
#include <QVector>
#include <cstdio>

int main() {
  printf("// Generated by tests/core/legacy/gen_lowercase_table.cpp from Qt %s.\n",
         QT_VERSION_STR);
  printf("// {code point, its lowercase} for every code point QString::toLower\n");
  printf("// changes into a single one, in order; U+0130 becomes two and is\n");
  printf("// handled by the code.\n");
  for (uint c = 0; c <= 0x10ffff; ++c) {
    if (c >= 0xd800 && c <= 0xdfff) continue;
    QString s = QString::fromUcs4(&c, 1), l = s.toLower();
    if (l == s) continue;
    QVector<uint> u = l.toUcs4();
    if (u.size() != 1) {
      if (c != 0x130) return fprintf(stderr, "unexpected %X\n", c), 1;
      continue;
    }
    printf("{0x%X, 0x%X},\n", c, u[0]);
  }
  return 0;
}
